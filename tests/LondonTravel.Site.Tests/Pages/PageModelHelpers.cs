namespace MartinCostello.LondonTravel.Site.Pages;

/// <summary>
/// A class containing helper methods for testing page models. This class cannot be inherited.
/// </summary>
internal static class PageModelHelpers
{
    /// <summary>
    /// The URLs for the pages of the site as generated by the application.
    /// </summary>
    private static readonly Dictionary<string, string> PageUrls = new(StringComparer.Ordinal)
    {
        [SiteRoutes.DeleteAccount] = "/manage/delete-account/",
        [SiteRoutes.Error] = "/error/",
        [SiteRoutes.ExternalSignIn] = "/account/external-sign-in/",
        [SiteRoutes.ExternalSignInCallback] = "/account/external-sign-in-callback/",
        [SiteRoutes.Help] = "/help/",
        [SiteRoutes.Home] = "/",
        [SiteRoutes.LinkAccount] = "/manage/link-account/",
        [SiteRoutes.LinkAccountCallback] = "/manage/link-account-callback/",
        [SiteRoutes.Manage] = "/manage/",
        [SiteRoutes.PrivacyPolicy] = "/privacy-policy/",
        [SiteRoutes.Register] = "/account/register/",
        [SiteRoutes.RemoveAccountLink] = "/manage/remove-account-link/",
        [SiteRoutes.RemoveAlexaLink] = "/manage/remove-alexa-link/",
        [SiteRoutes.SignIn] = "/account/sign-in/",
        [SiteRoutes.SignOut] = "/account/sign-out/",
        [SiteRoutes.Technology] = "/technology/",
        [SiteRoutes.TermsOfService] = "/terms-of-service/",
        [SiteRoutes.UpdateLinePreferences] = "/manage/update-line-preferences/",
    };

    public static SiteOptions CreateSiteOptions(bool isEnabled = true)
    {
        return new()
        {
            Authentication = new()
            {
                IsEnabled = isEnabled,
                ExternalProviders = new Dictionary<string, ExternalSignInOptions>()
                {
                    ["Amazon"] = new()
                    {
                        IsEnabled = isEnabled,
                        ClientId = "amazon-id",
                        ClientSecret = "amazon-secret",
                    },
                },
            },
        };
    }

    public static ClaimsPrincipal CreatePrincipal(bool isAuthenticated = true, params Claim[] claims)
    {
        var identity = isAuthenticated
            ? new ClaimsIdentity([new Claim(ClaimTypes.NameIdentifier, "user-id"), .. claims], "Test")
            : new ClaimsIdentity();

        return new ClaimsPrincipal(identity);
    }

    public static LondonTravelUser CreateUser(string? email = "john.smith@londontravel.martincostello.com")
    {
        return new()
        {
            CreatedAt = new DateTime(2017, 2, 4, 12, 34, 56, DateTimeKind.Utc),
            Email = email,
            ETag = "my-etag",
            FavoriteLines = ["district", "northern"],
            Id = "user-id",
            UserName = email,
        };
    }

    public static HttpContext CreateHttpContext(
        ITestOutputHelper outputHelper,
        ClaimsPrincipal? user = null,
        IAuthenticationService? authenticationService = null)
    {
        var serviceProvider = new ServiceCollection()
            .AddLogging((p) => p.AddXUnit(outputHelper))
            .AddSingleton(authenticationService ?? Substitute.For<IAuthenticationService>())
            .BuildServiceProvider();

        return new DefaultHttpContext()
        {
            RequestServices = serviceProvider,
            User = user ?? CreatePrincipal(),
        };
    }

    public static T WithPageContext<T>(this T page, HttpContext httpContext)
        where T : PageModel
    {
        var pageContext = new PageContext()
        {
            ActionDescriptor = new CompiledPageActionDescriptor(),
            HttpContext = httpContext,
            RouteData = new RouteData(),
            ViewData = new ViewDataDictionary(new EmptyModelMetadataProvider(), new ModelStateDictionary()),
        };

        page.PageContext = pageContext;
        page.Url = CreateUrlHelper(pageContext);

        return page;
    }

    public static UserManager<LondonTravelUser> CreateUserManager(
        ITestOutputHelper outputHelper,
        LondonTravelUser? user = null)
    {
        var manager = Substitute.For<UserManager<LondonTravelUser>>(
            Substitute.For<IUserStore<LondonTravelUser>>(),
            Substitute.For<IOptions<IdentityOptions>>(),
            Substitute.For<IPasswordHasher<LondonTravelUser>>(),
            new[] { Substitute.For<IUserValidator<LondonTravelUser>>() },
            new[] { Substitute.For<IPasswordValidator<LondonTravelUser>>() },
            Substitute.For<ILookupNormalizer>(),
            Substitute.For<IdentityErrorDescriber>(),
            Substitute.For<IServiceProvider>(),
            outputHelper.ToLogger<UserManager<LondonTravelUser>>());

        manager.GetUserAsync(Arg.Any<ClaimsPrincipal>())
               .Returns(Task.FromResult(user));

        if (user is not null)
        {
            manager.GetUserId(Arg.Any<ClaimsPrincipal>())
                   .Returns(user.Id);

            manager.GetUserIdAsync(user)
                   .Returns(Task.FromResult(user.Id!));
        }

        return manager;
    }

    public static SignInManager<LondonTravelUser> CreateSignInManager(
        ITestOutputHelper outputHelper,
        UserManager<LondonTravelUser> userManager)
    {
        var manager = Substitute.For<SignInManager<LondonTravelUser>>(
            userManager,
            Substitute.For<IHttpContextAccessor>(),
            Substitute.For<IUserClaimsPrincipalFactory<LondonTravelUser>>(),
            Substitute.For<IOptions<IdentityOptions>>(),
            outputHelper.ToLogger<SignInManager<LondonTravelUser>>(),
            Substitute.For<IAuthenticationSchemeProvider>(),
            Substitute.For<IUserConfirmation<LondonTravelUser>>());

        manager.ConfigureExternalAuthenticationProperties(Arg.Any<string?>(), Arg.Any<string?>(), Arg.Any<string?>())
               .Returns((_) => new AuthenticationProperties());

        return manager;
    }

    public static string PageUrl(string pageName, RouteValueDictionary? values = null)
    {
        string url = PageUrls[pageName];

        if (values is { Count: > 0 })
        {
            var query = values
                .Where((p) => !string.Equals(p.Key, "page", StringComparison.OrdinalIgnoreCase))
                .Where((p) => p.Value is not null)
                .Select((p) => KeyValuePair.Create(p.Key, p.Value?.ToString()));

            url = QueryHelpers.AddQueryString(url, query);
        }

        return url;
    }

    private static IUrlHelper CreateUrlHelper(ActionContext context)
    {
        var helper = Substitute.For<IUrlHelper>();

        helper.ActionContext.Returns(context);

        helper.IsLocalUrl(Arg.Any<string?>())
              .Returns((call) => call.Arg<string?>() is ['/', not ('/' or '\\'), ..] or ['/']);

        helper.RouteUrl(Arg.Any<UrlRouteContext>())
              .Returns((call) =>
              {
                  var routeContext = call.Arg<UrlRouteContext>();
                  var values = new RouteValueDictionary(routeContext.Values);
                  string pageName = values["page"]?.ToString() ?? string.Empty;

                  return PageUrl(pageName, values);
              });

        return helper;
    }
}
